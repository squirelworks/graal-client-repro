#!/usr/bin/env python3
"""Central index of the login tokens the client folders send.

Each client folder keeps its own token constant in its `src/*.pas`. This
script reads those constants (it changes nothing in the folders) and writes
`docs/token-index.md`, one row per folder. The evidence for each token is in
Graal_analysis `client-internals/version-token-catalogue.md`; the full token
list, including builds with no folder here, is seihai-core
`documentation/version-tokens.tsv`.

    python3 docs/token_index.py          # rewrite docs/token-index.md
    python3 docs/token_index.py --check  # exit 1 if it is stale, or a folder
                                         # name and its source disagree

It lives in docs/, not scripts/, because CI rebuilds every client when
anything under scripts/ changes. Rerun it after adding a folder or changing a
token constant.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "token-index.md"

# `Name = 'TOKEN';` in a const section. Comments and comparisons don't match.
CONST = re.compile(r"^\s*(\w+)\s*=\s*'(G(?:SERV|NW|3D|2N|NP|R3D)[0-9A-Z]{3,5})'\s*;")
# Constants that hold the listserver hello rather than the game login.
LIST_NAMES = {"ListVersionToken", "ListToken"}
# The token a folder name ends with, e.g. graal-2.22-GNW03014.
FOLDER_TOKEN = re.compile(r"-(G(?:SERV|NW|3D|2N|NP)[0-9A-Z]{3,5})$")


def folders():
    for d in sorted(ROOT.iterdir()):
        if d.is_dir() and (d / "src").is_dir() and not d.name.startswith("."):
            yield d


def scan(folder):
    login, listserver = {}, {}
    for pas in sorted((folder / "src").glob("*.pas")):
        for n, line in enumerate(pas.read_text(encoding="latin-1").splitlines(), 1):
            m = CONST.match(line)
            if not m:
                continue
            name, token = m.groups()
            where = f"`{pas.relative_to(ROOT).as_posix()}:{n}` (`{name}`)"
            (listserver if name in LIST_NAMES else login).setdefault(token, where)
    return login, listserver


def build():
    rows = []
    mismatches = []
    for d in folders():
        login, listserver = scan(d)
        named = FOLDER_TOKEN.search(d.name)
        named = named.group(1) if named else None
        if named and login and named not in login:
            mismatches.append(f"{d.name}: folder name says {named}, source sends {', '.join(login)}")
        login_s = ", ".join(f"`{t}`" for t in login) or "none"
        list_s = ", ".join(f"`{t}`" for t in listserver) or "-"
        where = "<br>".join(list(login.values()) + list(listserver.values())) or "-"
        rows.append(f"| `{d.name}` | {login_s} | {list_s} | {where} |")
    out = [
        "# Login token index",
        "",
        "Generated by `docs/token_index.py` from the token constants in each folder's",
        "`src/*.pas`; do not edit by hand. Rerun it after adding a folder or changing",
        "a token constant (`--check` says whether it is current).",
        "",
        "Each folder still owns its constant; this page only collects them. The",
        "evidence grade of each token is in Graal_analysis",
        "`client-internals/version-token-catalogue.md`. Every known token, with or",
        "without a folder here, is in seihai-core `documentation/version-tokens.tsv`.",
        "\"none\" means the folder sends no token constant: a pre-token build, an",
        "offline build, or a 6.11+ client whose token comes from the server's",
        "connector script.",
        "",
        "| Folder | Login token | Listserver hello | Defined at |",
        "|---|---|---|---|",
        *rows,
        "",
    ]
    if mismatches:
        out += ["## Folder name and source disagree", ""]
        out += [f"- {m}" for m in mismatches]
        out.append("")
    return "\n".join(out)


def main(argv):
    text = build()
    if "--check" in argv:
        if "## Folder name and source disagree" in text:
            print(text.split("## Folder name and source disagree", 1)[1].strip(), file=sys.stderr)
            return 1
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/token-index.md is stale; run: python3 docs/token_index.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
