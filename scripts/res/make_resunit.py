#!/usr/bin/env python3
"""Compile a build's extracted resources into a Pascal unit.

Each build that reproduces an original client keeps the files it took out
of that client's own program in <build>/res/ (pictures, forms, icons; see
the README.md there for where each came from). This script turns them into
<build>/src/<Unit>.pas, so the rebuilt program carries them on every
platform and never needs the original program at run time.

    python3 scripts/res/make_resunit.py graal-2.31-GNW28015 Res231
    python3 scripts/res/make_resunit.py --check graal-2.31-GNW28015 Res231

The unit offers ResFile(Name, Data): the file's bytes by its name without
extension, in any case (SCREENIMG1, BUTTON2, ...). --check exits 1 when the
unit is out of date.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def unit_text(build, unit, files):
    out = []
    out.append("{ %s: the resources %s takes from the original client's own\n"
               "  program, compiled in. GENERATED by scripts/res/make_resunit.py from\n"
               "  %s/res/ (its README.md says where each file came from); do not\n"
               "  edit by hand. }" % (unit, build, build))
    out.append("unit %s;\n\n{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}\n\ninterface\n" % unit)
    out.append("{ The bytes of the compiled-in file Name (no extension, any case), or\n"
               "  False when there is none. }\n"
               "function ResFile(const Name: string; out Data: string): Boolean;\n")
    out.append("implementation\n\nuses\n  SysUtils;\n\nconst")
    names = []
    for i, (name, data) in enumerate(files):
        names.append(name)
        out.append("  R%d: array[0..%d] of Byte = (" % (i, len(data) - 1))
        rows = []
        for j in range(0, len(data), 18):
            rows.append("    " + ",".join("$%02x" % b for b in data[j:j + 18]))
        out.append(",\n".join(rows) + ");")
    out.append("  Names: array[0..%d] of string = (\n    %s);\n" % (
        len(names) - 1, ",\n    ".join("'%s'" % n for n in names)))
    out.append("function Bytes(const B: array of Byte): string;\nbegin\n"
               "  SetLength(Result, Length(B));\n"
               "  if Length(B) > 0 then Move(B[0], Result[1], Length(B));\nend;\n")
    out.append("function ResFile(const Name: string; out Data: string): Boolean;\nvar\n"
               "  I: Integer;\nbegin\n  Data := '';\n  Result := False;\n"
               "  for I := 0 to High(Names) do\n"
               "    if SameText(Names[I], Name) then\n    begin\n      case I of")
    for i in range(len(files)):
        out.append("        %d: Data := Bytes(R%d);" % (i, i))
    out.append("      end;\n      Result := True;\n      Exit;\n    end;\nend;\n\nend.")
    return "\n".join(out) + "\n"


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    build, unit = args
    res = os.path.join(ROOT, build, "res")
    files = []
    for fn in sorted(os.listdir(res)):
        base, ext = os.path.splitext(fn)
        if fn.lower() == "readme.md" or ext.lower() == ".ico":
            continue  # the icon goes in through the .rc
        with open(os.path.join(res, fn), "rb") as f:
            files.append((base.upper(), f.read()))
    text = unit_text(build, unit, files)
    path = os.path.join(ROOT, build, "src", unit + ".pas")
    old = open(path).read() if os.path.exists(path) else ""
    if check:
        if old != text:
            print("%s is out of date" % path)
            sys.exit(1)
        return
    with open(path, "w") as f:
        f.write(text)
    print("wrote %s (%d files)" % (path, len(files)))


if __name__ == "__main__":
    main()
