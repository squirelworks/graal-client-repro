#!/usr/bin/env python3
"""Writes common/GUiFont.pas: the dialog text of the original-style
windows (the 2.22 start window and server list), 14 px high as their
forms ask (Font.Height -14, MS Sans Serif), in a regular and a bold face,
and the bigger bold of the 2.0x start window's buttons (16 px, as 12 pt
bold draws on Windows). Characters 32 to 255 as Windows-1252 has them
(the 2.0x language box lists Espa\xf1ol, Fran\xe7ais, Portugu\xeas).

The glyphs are rendered here from Liberation Sans (SIL Open Font License
1.1, metric-compatible with Arial), one bit per pixel without smoothing,
as Windows of 2001 drew MS Sans Serif. Run:
  python3 scripts/builtin/make_uifont.py [regular.ttf bold.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

REG = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf'
BOLD = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'
SIZE = 13      # pixel em; a 14 px line as the forms' TextHeight 16 allows
LINE = 16
BTN_SIZE = 16  # the 2.0x start window's buttons
BTN_LINE = 20
# The 2.0x status display's key letters, as the real client draws them
# (traced under Wine, WINEDEBUG=+font): GDI text in "Helvetica" bold (Arial
# on Windows; Liberation Sans is metric-compatible) with a cell height of
# 26 (A, S, D) and 10 (the small Q), the top of the cell at the point given.
def cell(h):
    em = h * 2048 / (1854 + 434)        # Arial's ascent + descent
    return em, h, round(1854 * em / 2048)
FIRST, LAST = 32, 255

def char(c):
    try:
        return bytes([c]).decode('cp1252')
    except UnicodeDecodeError:
        return '?'

def face(path, size=SIZE, line=LINE, base=None):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    top = (line - (asc + desc)) // 2
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = char(c)
        adv = int(round(f.getlength(ch)))
        w = max(adv, 1) + 2
        img = Image.new('L', (w, line), 0)
        if base is None:
            ImageDraw.Draw(img).text((0, top), ch, font=f, fill=255)
        else:
            # GDI: the cell's top at 0, the baseline at its ascent
            ImageDraw.Draw(img).text((0, base), ch, font=f, fill=255, anchor='ls')
        px = img.load()
        rows = []
        for y in range(line):
            bits = 0
            for x in range(w):
                if px[x, y] >= 128:
                    bits |= 1 << x
            rows.append(bits)
        glyphs.append((adv, w, rows))
    return glyphs

def pas_face(name, glyphs, line=LINE):
    out = []
    out.append('  %sAdv: array[%d..%d] of Byte = (' % (name, FIRST, LAST))
    out.append('    ' + ', '.join(str(g[0]) for g in glyphs) + ');')
    out.append('  %sW: array[%d..%d] of Byte = (' % (name, FIRST, LAST))
    out.append('    ' + ', '.join(str(g[1]) for g in glyphs) + ');')
    out.append('  %sRows: array[%d..%d, 0..%d] of Cardinal = (' % (name, FIRST, LAST, line - 1))
    lines = []
    for g in glyphs:
        lines.append('    (' + ', '.join('$%X' % r for r in g[2]) + ')')
    out.append(',\n'.join(lines) + ');')
    return '\n'.join(out)

reg = face(REG)
bold = face(BOLD)
btn = face(BOLD, BTN_SIZE, BTN_LINE)
HUD_LINE = 26
hud = face(BOLD, *cell(26))
hud_small = face(BOLD, *cell(10))
src = '''{ GUiFont: the text of the original-style dialogs, 16 px lines, regular
  and bold. GENERATED by scripts/builtin/make_uifont.py from Liberation
  Sans (SIL Open Font License 1.1); do not edit by hand. }
unit GUiFont;

{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}

interface

uses
  GSurface;

type
  { ufButton: the 2.0x start window's button captions, bold and bigger;
    ufHud, ufHudSmall: the 2.0x status display's key letters, as GDI draws
    "Helvetica" bold with a cell 26 (A, S, D) and 10 (Q) high, Y the top of
    the cell }
  TUiFace = (ufRegular, ufBold, ufButton, ufHud, ufHudSmall);

const
  UiLineH = %d;
  UiHudLineH = %d;

{ Width in pixels of S. }
function UiTextWidth(const S: string; Face: TUiFace): Integer;
{ Draws S with the top of its 16 px line at Y (ufButton: its line is
  16 px too, the letters reaching above and below it). }
procedure UiDrawText(Dest: TGSurface; X, Y: Integer; const S: string; Color: Cardinal;
  Face: TUiFace);

implementation

const
%s
%s
%s
%s
%s

function UiTextWidth(const S: string; Face: TUiFace): Integer;
var
  I, C: Integer;
begin
  Result := 0;
  for I := 1 to Length(S) do
  begin
    C := Ord(S[I]);
    if (C < %d) or (C > %d) then C := Ord('?');
    case Face of
      ufBold: Inc(Result, BoldAdv[C]);
      ufButton: Inc(Result, BtnAdv[C]);
      ufHud: Inc(Result, HudAdv[C]);
      ufHudSmall: Inc(Result, HudsAdv[C]);
    else
      Inc(Result, RegAdv[C]);
    end;
  end;
end;

procedure UiDrawText(Dest: TGSurface; X, Y: Integer; const S: string; Color: Cardinal;
  Face: TUiFace);
var
  I, C, R, B, W, PX, PY, LastRow: Integer;
  Bits: Cardinal;
begin
  for I := 1 to Length(S) do
  begin
    C := Ord(S[I]);
    if (C < %d) or (C > %d) then C := Ord('?');
    case Face of
      ufBold: W := BoldW[C];
      ufButton: W := BtnW[C];
      ufHud: W := HudW[C];
      ufHudSmall: W := HudsW[C];
    else
      W := RegW[C];
    end;
    case Face of
      ufButton: LastRow := %d;
      ufHud: LastRow := UiHudLineH - 1;
      ufHudSmall: LastRow := 9;
    else
      LastRow := UiLineH - 1;
    end;
    for R := 0 to LastRow do
    begin
      case Face of
        ufBold: Bits := BoldRows[C, R];
        ufButton: Bits := BtnRows[C, R];
        ufHud: Bits := HudRows[C, R];
        ufHudSmall: Bits := HudsRows[C, R];
      else
        Bits := RegRows[C, R];
      end;
      if Bits = 0 then Continue;
      if Face = ufButton then PY := Y + R - %d else PY := Y + R;
      if (PY < 0) or (PY >= Dest.Height) then Continue;
      for B := 0 to W - 1 do
        if Bits and (Cardinal(1) shl B) <> 0 then
        begin
          PX := X + B;
          if (PX >= 0) and (PX < Dest.Width) then Dest.Pixels[PX + PY * Dest.Width] := Color;
        end;
    end;
    case Face of
      ufBold: Inc(X, BoldAdv[C]);
      ufButton: Inc(X, BtnAdv[C]);
      ufHud: Inc(X, HudAdv[C]);
      ufHudSmall: Inc(X, HudsAdv[C]);
    else
      Inc(X, RegAdv[C]);
    end;
  end;
end;

end.
''' % (LINE, HUD_LINE,
       pas_face('Reg', reg), pas_face('Bold', bold), pas_face('Btn', btn, BTN_LINE),
       pas_face('Hud', hud, HUD_LINE), pas_face('Huds', hud_small, 10),
       FIRST, LAST, FIRST, LAST, BTN_LINE - 1, (BTN_LINE - LINE) // 2)
open(sys.argv[3] if len(sys.argv) > 3 else 'common/GUiFont.pas', 'w').write(src)
