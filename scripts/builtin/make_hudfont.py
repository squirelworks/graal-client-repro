#!/usr/bin/env python3
"""Writes common/GHudFont.pas: the text the 2.1-era clients draw over the
board with GDI, as traced from the real Graal-NewMain26.exe under Wine
(WINEDEBUG=+font): CreateFontIndirect with a positive lfHeight (the cell
height) and weight 700, then ExtTextOut twice, the shadow at +1,+1 first.

  hfKey   "Helvetica" 26: the A, S and D key letters
  hfHint  "Helvetica" 10: the Q over D
  hfName  "Tempus Sans ITC" 24: the sword power and the nicknames, when
          the install has no TEMPSITC.TTF (HudNameText draws with the
          install's own copy, as the exe's AddFontResource does)
  hfNwKey "b" 24, weight 400: Graal-NW.exe's key letters; Windows maps
          that unknown face to Arial

Windows substitutes Arial for Helvetica (FontSubstitutes); Tempus Sans
ITC comes with Office and is not redistributable, so it takes the same
Arial fallback Windows uses when it is missing. The glyphs are rendered
from Liberation Sans Bold (SIL Open Font License 1.1, metric-compatible
with Arial) at the em GDI picks for the cell height, with 4-bit coverage
for the smoothing Windows applies. Run:
  python3 scripts/builtin/make_hudfont.py [bold.ttf regular.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BOLD = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'
REG = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf'
UPM, ASC, DESC = 2048, 1854, 434      # Arial's head and OS/2 win metrics
FIRST, LAST = 32, 126
FACES = [('hfKey', 26, True), ('hfHint', 10, True), ('hfName', 24, True), ('hfNwKey', 24, False)]

def face(cell, bold):
    em = int(cell * UPM / (ASC + DESC))         # GDI keeps tmHeight <= cell
    asc = round(em * ASC / UPM)
    f = ImageFont.truetype(BOLD if bold else REG, em)
    out = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = int(round(f.getlength(ch)))
        w = adv + 4
        img = Image.new('L', (w, cell), 0)
        ImageDraw.Draw(img).text((2, asc), ch, font=f, fill=255, anchor='ls')
        bb = img.getbbox()
        if bb is None:
            out.append((adv, 0, 0, 0, 0, ''))
            continue
        x0, y0, x1, y1 = bb
        px = img.load()
        hexs = ''.join('%x' % round(px[x, y] * 15 / 255)
                       for y in range(y0, y1) for x in range(x0, x1))
        out.append((adv, x0 - 2, y0, x1 - x0, y1 - y0, hexs))
    return out

def main():
    L = []
    L.append('{ GHudFont: the GDI text the 2.1-era clients draw over the board (key')
    L.append('  letters, the Q hint, sword power, nicknames). GENERATED by')
    L.append('  scripts/builtin/make_hudfont.py from Liberation Sans Bold (SIL Open')
    L.append('  Font License 1.1); do not edit by hand. }')
    L.append('unit GHudFont;\n\n{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}\n\ninterface\n\nuses\n  GSurface;\n')
    L.append('type\n  THudFace = (' + ', '.join(n for n, _, _ in FACES) + ');\n')
    L.append('{ Width in pixels of S. }')
    L.append('function HudTextWidth(const S: string; Face: THudFace): Integer;')
    L.append('{ Draws S with the top of its cell at (X, Y), as ExtTextOut with TA_TOP. }')
    L.append('procedure HudDrawText(Dest: TGSurface; X, Y: Integer; const S: string;')
    L.append('  Color: Cardinal; Face: THudFace);')
    L.append('{ The traced two-pass draw: S in Shadow at (X + 1, Y + 1), then in Color at (X, Y). }')
    L.append('procedure HudShadowText(Dest: TGSurface; X, Y: Integer; const S: string;')
    L.append('  Color, Shadow: Cardinal; Face: THudFace);\n')
    L.append('{ Width of S in the names font. }')
    L.append('function HudNameWidth(const S: string): Integer;')
    L.append('{ "Tempus Sans ITC" 24 bold, the font the exe loads from the install\'s')
    L.append('  tempsitc.ttf (AddFontResourceA), shadow at +1,+1 first; hfName when')
    L.append('  the install has none. }')
    L.append('procedure HudNameText(Dest: TGSurface; X, Y: Integer; const S: string;')
    L.append('  Color, Shadow: Cardinal);\n')
    L.append('implementation\n\nuses\n  GAssetDirs, GTrueType;\n')
    L.append('type\n  TGlyph = record Adv, OX, OY, W, H: Integer; Cov: string; end;\n')
    L.append('const')
    for name, cell, bold in FACES:
        gl = face(cell, bold)
        L.append('  G_%s: array[%d..%d] of TGlyph = (' % (name, FIRST, LAST))
        items = []
        for adv, ox, oy, w, h, hexs in gl:
            chunks = [hexs[i:i + 96] for i in range(0, len(hexs), 96)] or ['']
            s = " + ".join("'%s'" % c for c in chunks)
            items.append('    (Adv: %d; OX: %d; OY: %d; W: %d; H: %d; Cov: %s)' % (adv, ox, oy, w, h, s))
        L.append(',\n'.join(items) + ');')
    L.append('''
function Glyph(Face: THudFace; C: Char): TGlyph;
var
  N: Integer;
begin
  N := Ord(C);
  if (N < 32) or (N > 126) then N := Ord('?');
  case Face of
    hfKey: Result := G_hfKey[N];
    hfHint: Result := G_hfHint[N];
    hfNwKey: Result := G_hfNwKey[N];
  else
    Result := G_hfName[N];
  end;
end;

function HudTextWidth(const S: string; Face: THudFace): Integer;
var
  I: Integer;
begin
  Result := 0;
  for I := 1 to Length(S) do Inc(Result, Glyph(Face, S[I]).Adv);
end;

function HexNib(C: Char): Integer;
begin
  if C <= '9' then Result := Ord(C) - Ord('0') else Result := Ord(C) - Ord('a') + 10;
end;

procedure HudDrawText(Dest: TGSurface; X, Y: Integer; const S: string;
  Color: Cardinal; Face: THudFace);
var
  I, R, C, PX, PY, A, K: Integer;
  G: TGlyph;
  D: Cardinal;
  function Mix(Sh: Integer): Cardinal;
  begin
    Result := (((Color shr Sh) and $FF) * Cardinal(A) + ((D shr Sh) and $FF) * Cardinal(15 - A)) div 15;
  end;
begin
  for I := 1 to Length(S) do
  begin
    G := Glyph(Face, S[I]);
    K := 1;
    for R := 0 to G.H - 1 do
      for C := 0 to G.W - 1 do
      begin
        A := HexNib(G.Cov[K]);
        Inc(K);
        PX := X + G.OX + C;
        PY := Y + G.OY + R;
        if (A = 0) or (PX < 0) or (PY < 0) or (PX >= Dest.Width) or (PY >= Dest.Height) then Continue;
        D := Dest.Pixels[PY * Dest.Width + PX];
        Dest.Pixels[PY * Dest.Width + PX] := $FF000000 or (Mix(16) shl 16) or (Mix(8) shl 8) or Mix(0);
      end;
    Inc(X, G.Adv);
  end;
end;

procedure HudShadowText(Dest: TGSurface; X, Y: Integer; const S: string;
  Color, Shadow: Cardinal; Face: THudFace);
begin
  HudDrawText(Dest, X + 1, Y + 1, S, Shadow, Face);
  HudDrawText(Dest, X, Y, S, Color, Face);
end;

var
  NameTtf: TTrueTypeFont;
  NameTried: Boolean;
  NamePx: Integer;

function NameFont: TTrueTypeFont;
var
  F: string;
begin
  if not NameTried then
  begin
    NameTried := True;
    F := AssetPath('TEMPSITC.TTF');
    if F = '' then F := AssetPath('tempsitc.ttf');
    if F <> '' then
    begin
      NameTtf := TTrueTypeFont.Create;
      if NameTtf.LoadFromFile(F) then
      begin
        { a positive lfHeight is the cell: the largest em whose line fits 24 }
        NamePx := 24;
        while (NamePx > 1) and (NameTtf.LineHeight(NamePx) > 24) do Dec(NamePx);
      end
      else
      begin
        NameTtf.Free;
        NameTtf := nil;
      end;
    end;
  end;
  Result := NameTtf;
end;

function HudNameWidth(const S: string): Integer;
begin
  if NameFont <> nil then Result := NameFont.TextWidth(S, NamePx, True)
  else Result := HudTextWidth(S, hfName);
end;

procedure HudNameText(Dest: TGSurface; X, Y: Integer; const S: string;
  Color, Shadow: Cardinal);
begin
  if NameFont = nil then
  begin
    HudShadowText(Dest, X, Y, S, Color, Shadow, hfName);
    Exit;
  end;
  NameTtf.DrawText(Dest, X + 1, Y + 1, S, NamePx, Shadow, True);
  NameTtf.DrawText(Dest, X, Y, S, NamePx, Color, True);
end;

initialization

finalization
  NameTtf.Free;

end.''')
    open('common/GHudFont.pas', 'w').write('\n'.join(L) + '\n')

main()
