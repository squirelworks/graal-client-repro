#!/usr/bin/env python3
"""Writes common/GNpcFont.pas: the text the 1.3x and 1.4x clients draw in
the game view (NPC messages and the names under characters), Arial Bold
20 px with 24 px lines, as measured on the real clients on Windows 10
(the line "If you have problems, then just press F1 and click on 'More"
is 556 px wide there; Arial Bold 20 px gives 562 with the bearing).

The glyphs are rendered from Liberation Sans Bold (SIL Open Font License
1.1, metric-compatible with Arial), one bit per pixel. Run:
  python3 scripts/builtin/make_npcfont.py [bold.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BOLD = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'
SIZE = 20
LINE = 24
FIRST, LAST = 32, 126

f = ImageFont.truetype(BOLD, SIZE)
asc, desc = f.getmetrics()
top = (LINE - (asc + desc)) // 2
glyphs = []
for c in range(FIRST, LAST + 1):
    ch = chr(c)
    adv = int(round(f.getlength(ch)))
    w = min(max(adv, 1) + 2, 32)
    img = Image.new('L', (w, LINE), 0)
    ImageDraw.Draw(img).text((0, top), ch, font=f, fill=255)
    px = img.load()
    rows = []
    for y in range(LINE):
        bits = 0
        for x in range(w):
            if px[x, y] >= 128:
                bits |= 1 << x
        rows.append(bits)
    glyphs.append((adv, w, rows))

tab = []
tab.append('  NpcAdv: array[%d..%d] of Byte = (' % (FIRST, LAST))
tab.append('    ' + ', '.join(str(g[0]) for g in glyphs) + ');')
tab.append('  NpcW: array[%d..%d] of Byte = (' % (FIRST, LAST))
tab.append('    ' + ', '.join(str(g[1]) for g in glyphs) + ');')
tab.append('  NpcRows: array[%d..%d, 0..%d] of Cardinal = (' % (FIRST, LAST, LINE - 1))
tab.append(',\n'.join('    (' + ', '.join('$%X' % r for r in g[2]) + ')' for g in glyphs) + ');')

src = '''{ GNpcFont: the game view's text in the 1.3x and 1.4x clients (NPC
  messages, names under characters): Arial Bold 20 px, 24 px lines.
  GENERATED by scripts/builtin/make_npcfont.py from Liberation Sans Bold
  (SIL Open Font License 1.1); do not edit by hand. }
unit GNpcFont;

{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}

interface

uses
  Classes, GSurface;

const
  NpcLineH = %(line)d;

{ Width in pixels of S. }
function NpcTextWidth(const S: string): Integer;
{ Draws S with the top of its line at Y. }
procedure NpcDrawText(Dest: TGSurface; X, Y: Integer; const S: string; Color: Cardinal);
{ White on a blue shadow one pixel down and right, as the clients draw it. }
procedure NpcDrawShadowed(Dest: TGSurface; X, Y: Integer; const S: string);
{ Splits S into lines no wider than MaxW, at spaces (a word wider than
  MaxW stands alone). }
procedure NpcWrap(const S: string; MaxW: Integer; Lines: TStrings);

implementation

const
%(tab)s

function NpcTextWidth(const S: string): Integer;
var
  I, C: Integer;
begin
  Result := 0;
  for I := 1 to Length(S) do
  begin
    C := Ord(S[I]);
    if (C < %(first)d) or (C > %(last)d) then C := Ord('?');
    Inc(Result, NpcAdv[C]);
  end;
end;

procedure NpcDrawText(Dest: TGSurface; X, Y: Integer; const S: string; Color: Cardinal);
var
  I, C, R, B, PX, PY: Integer;
  Bits: Cardinal;
begin
  for I := 1 to Length(S) do
  begin
    C := Ord(S[I]);
    if (C < %(first)d) or (C > %(last)d) then C := Ord('?');
    for R := 0 to NpcLineH - 1 do
    begin
      Bits := NpcRows[C, R];
      if Bits = 0 then Continue;
      PY := Y + R;
      if (PY < 0) or (PY >= Dest.Height) then Continue;
      for B := 0 to NpcW[C] - 1 do
        if Bits and (Cardinal(1) shl B) <> 0 then
        begin
          PX := X + B;
          if (PX >= 0) and (PX < Dest.Width) then Dest.Pixels[PX + PY * Dest.Width] := Color;
        end;
    end;
    Inc(X, NpcAdv[C]);
  end;
end;

procedure NpcDrawShadowed(Dest: TGSurface; X, Y: Integer; const S: string);
begin
  NpcDrawText(Dest, X + 1, Y + 1, S, $FF0000FF);
  NpcDrawText(Dest, X, Y, S, $FFFFFFFF);
end;

procedure NpcWrap(const S: string; MaxW: Integer; Lines: TStrings);
var
  Line, Word, Rest: string;
  P: Integer;
begin
  Lines.Clear;
  Line := '';
  Rest := S;
  while Rest <> '' do
  begin
    P := Pos(' ', Rest);
    if P = 0 then
    begin
      Word := Rest;
      Rest := '';
    end
    else
    begin
      Word := Copy(Rest, 1, P - 1);
      Rest := Copy(Rest, P + 1, MaxInt);
    end;
    if Line = '' then Line := Word
    else if NpcTextWidth(Line + ' ' + Word) <= MaxW then Line := Line + ' ' + Word
    else
    begin
      Lines.Add(Line);
      Line := Word;
    end;
  end;
  if Line <> '' then Lines.Add(Line);
end;

end.
''' % {'line': LINE, 'tab': '\n'.join(tab), 'first': FIRST, 'last': LAST}
open(sys.argv[2] if len(sys.argv) > 2 else 'common/GNpcFont.pas', 'w').write(src)
