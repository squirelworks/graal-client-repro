#!/usr/bin/env python3
"""Writes graal-2.22-GNW03014/src/Res222.pas: the resources the real
Graal_222.exe carries and the rebuild uses (its RCDATA: the start window
art SCREENIMG1/2, the buttons BUTTON1..4, the Training levels
TUTORIALA1..C3; and languages/languageEnglish.txt as LANGUAGEENGLISH),
compiled into the rebuild so it runs with no Graal_222.exe beside it.

The bytes come from graal-2.22-GNW03014/res/, one file per resource,
named as the resource. Run from the repository root:
  python3 scripts/builtin/make_res222.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, 'graal-2.22-GNW03014', 'res')
OUT = os.path.join(ROOT, 'graal-2.22-GNW03014', 'src', 'Res222.pas')

names = sorted(n for n in os.listdir(RES) if not n.startswith('.'))
o = []
o.append('{ Res222: the resources of the real Graal_222.exe (its RCDATA) and its')
o.append('  English language file, compiled in. Generated by')
o.append('  scripts/builtin/make_res222.py from graal-2.22-GNW03014/res/; do not')
o.append('  edit. }')
o.append('unit Res222;')
o.append('')
o.append('{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}')
o.append('')
o.append('interface')
o.append('')
o.append('{ The bytes of the resource Name (as the real exe names it, any case);')
o.append('  False when the rebuild carries none by that name. }')
o.append('function EmbeddedRes(const Name: string; out Data: string): Boolean;')
o.append('')
o.append('implementation')
o.append('')
o.append('uses')
o.append('  SysUtils;')
o.append('')
o.append('const')
for i, n in enumerate(names):
    d = open(os.path.join(RES, n), 'rb').read()
    o.append('  R%d: array[0..%d] of Byte = (' % (i, len(d) - 1))
    for k in range(0, len(d), 20):
        chunk = ','.join('$%02X' % b for b in d[k:k + 20])
        o.append('    ' + chunk + (',' if k + 20 < len(d) else ');'))
o.append('')
o.append('procedure Take(const Bytes: array of Byte; out Data: string);')
o.append('begin')
o.append('  SetLength(Data, Length(Bytes));')
o.append('  if Length(Bytes) > 0 then Move(Bytes[0], Data[1], Length(Bytes));')
o.append('end;')
o.append('')
o.append('function EmbeddedRes(const Name: string; out Data: string): Boolean;')
o.append('var')
o.append('  N: string;')
o.append('begin')
o.append('  Data := \'\';')
o.append('  Result := True;')
o.append('  N := UpperCase(Name);')
for i, n in enumerate(names):
    o.append("  if N = '%s' then begin Take(R%d, Data); Exit; end;" % (n.upper(), i))
o.append('  Result := False;')
o.append('end;')
o.append('')
o.append('end.')
open(OUT, 'w', newline='\n').write('\n'.join(o) + '\n')
print('wrote', OUT, len(names), 'resources')
