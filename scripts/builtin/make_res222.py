#!/usr/bin/env python3
"""Writes graal-2.22-GNW03014/src/Res222.pas: what the rebuild carries of
the real 2.22, so it runs and looks like 2.22 with nothing beside it.

- graal-2.22-GNW03014/res/<NAME>: the RCDATA of the real Graal_222.exe
  (the start window art SCREENIMG1/2, the buttons BUTTON1..4, the
  Training levels TUTORIALA1..C3) and languages/languageEnglish.txt as
  LANGUAGEENGLISH, by resource name;
- graal-2.22-GNW03014/res/install/<path>: files of the 2.22 install the
  game reads (tile sheets, sprites, the tutorial's map, ganis and
  pictures, the default body, head, sword and shield, arrays.dat, the
  name font), by their path in the install.

Each file is kept as base64 text in the unit and decoded when asked for.
Run from the repository root:
  python3 scripts/builtin/make_res222.py
"""
import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, 'graal-2.22-GNW03014', 'res')
OUT = os.path.join(ROOT, 'graal-2.22-GNW03014', 'src', 'Res222.pas')
CHUNK = 200

named = sorted(n for n in os.listdir(RES)
               if os.path.isfile(os.path.join(RES, n)) and not n.startswith('.'))
inst = []
base = os.path.join(RES, 'install')
for d, _, fs in os.walk(base):
    for f in fs:
        p = os.path.join(d, f)
        inst.append(os.path.relpath(p, base).replace(os.sep, '/'))
inst.sort(key=str.lower)

entries = [(n.upper(), os.path.join(RES, n)) for n in named] + \
          [(r.lower(), os.path.join(base, r)) for r in inst]

import hashlib
h = hashlib.sha1()
for key, path in entries:
    h.update(key.encode()); h.update(open(path, 'rb').read())
STAMP = h.hexdigest()[:8]

o = []
w = o.append
w('{ Res222: what the rebuild carries of the real 2.22: the resources of')
w('  its Graal_222.exe (RCDATA, by name), its English language file, and')
w('  the files of its install that the game reads (by path, lower case).')
w('  Generated by scripts/builtin/make_res222.py from')
w('  graal-2.22-GNW03014/res/; do not edit. }')
w('unit Res222;')
w('')
w('{$IFDEF FPC}{$MODE DELPHI}{$H+}{$ENDIF}')
w('')
w('interface')
w('')
w('{ The resource Name of the real exe (any case), or an install file by its')
w('  path (any case, / or \\); False when the rebuild carries none. }')
w('function EmbeddedRes(const Name: string; out Data: string): Boolean;')
w('{ The install files carried, for the asset fallback and tests. }')
w('function EmbeddedCount: Integer;')
w('function EmbeddedName(I: Integer): string;')
w('{ The path of an install file carried, written out once to a folder of')
w('  the user\'s temporary files so code that reads files can open it; \'\'')
w('  when it is not carried or cannot be written. }')
w('function EmbeddedPath(const Rel: string): string;')
w('')
w('implementation')
w('')
w('uses')
w('  SysUtils, Classes;')
w('')
w('const')
for i, (key, path) in enumerate(entries):
    b = base64.b64encode(open(path, 'rb').read()).decode('ascii')
    parts = [b[k:k + CHUNK] for k in range(0, len(b), CHUNK)] or ['']
    w('  D%d: array[0..%d] of string = (' % (i, len(parts) - 1))
    for k, p in enumerate(parts):
        w("    '%s'%s" % (p, ',' if k + 1 < len(parts) else ');'))
w('')
w('  Names: array[0..%d] of string = (' % (len(entries) - 1))
for i, (key, _) in enumerate(entries):
    w("    '%s'%s" % (key, ',' if i + 1 < len(entries) else ');'))
w('')
w('function Decode64(const Parts: array of string): string;')
w('var')
w('  I, J, V, Bits, N: Integer;')
w('  C: Char;')
w('  S: string;')
w('begin')
w('  N := 0;')
w('  for I := 0 to High(Parts) do Inc(N, Length(Parts[I]));')
w('  SetLength(Result, (N div 4) * 3);')
w('  N := 0;')
w('  V := 0;')
w('  Bits := 0;')
w('  for I := 0 to High(Parts) do')
w('  begin')
w('    S := Parts[I];')
w('    for J := 1 to Length(S) do')
w('    begin')
w('      C := S[J];')
w("      case C of")
w("        'A'..'Z': V := (V shl 6) or (Ord(C) - Ord('A'));")
w("        'a'..'z': V := (V shl 6) or (Ord(C) - Ord('a') + 26);")
w("        '0'..'9': V := (V shl 6) or (Ord(C) - Ord('0') + 52);")
w("        '+': V := (V shl 6) or 62;")
w("        '/': V := (V shl 6) or 63;")
w('      else')
w('        Continue;')
w('      end;')
w('      Inc(Bits, 6);')
w('      if Bits >= 8 then')
w('      begin')
w('        Dec(Bits, 8);')
w('        Inc(N);')
w('        Result[N] := Chr((V shr Bits) and $FF);')
w('      end;')
w('      V := V and ((1 shl Bits) - 1);')
w('    end;')
w('  end;')
w('  SetLength(Result, N);')
w('end;')
w('')
w('function Lookup(const Key: string): Integer;')
w('var')
w('  I: Integer;')
w('begin')
w('  for I := 0 to High(Names) do')
w('    if Names[I] = Key then')
w('    begin')
w('      Result := I;')
w('      Exit;')
w('    end;')
w('  Result := -1;')
w('end;')
w('')
w('function Take(I: Integer): string;')
w('begin')
w('  case I of')
for i in range(len(entries)):
    w('    %d: Result := Decode64(D%d);' % (i, i))
w('  else')
w("    Result := '';")
w('  end;')
w('end;')
w('')
w('function EmbeddedRes(const Name: string; out Data: string): Boolean;')
w('var')
w('  I: Integer;')
w('begin')
w("  Data := '';")
w('  I := Lookup(UpperCase(Name));')
w("  if I < 0 then I := Lookup(LowerCase(StringReplace(Name, '\\', '/', [rfReplaceAll])));")
w('  Result := I >= 0;')
w('  if Result then Data := Take(I);')
w('end;')
w('')
w('function EmbeddedCount: Integer;')
w('begin')
w('  Result := %d;' % len(inst))
w('end;')
w('')
w('function EmbeddedName(I: Integer): string;')
w('begin')
w("  if (I >= 0) and (I < %d) then Result := Names[%d + I] else Result := '';" % (len(inst), len(named)))
w('end;')
w('')
w('function EmbeddedPath(const Rel: string): string;')
w('var')
w('  Key, F, D: string;')
w('  S: TFileStream;')
w('begin')
w("  Result := '';")
w("  Key := LowerCase(StringReplace(Rel, '\\', '/', [rfReplaceAll]));")
w("  if (Key = '') or (Pos('..', Key) > 0) or (Lookup(Key) < %d) then Exit;" % len(named))
w("  { a folder per set of files, so a newer build never reads an older one's }")
w("  F := IncludeTrailingPathDelimiter(GetTempDir(False)) + 'graal-delphi-2.22-%s' + PathDelim +" % STAMP)
w("    StringReplace(Key, '/', PathDelim, [rfReplaceAll]);")
w('  if FileExists(F) then')
w('  begin')
w('    Result := F;')
w('    Exit;')
w('  end;')
w('  if not EmbeddedRes(Key, D) then Exit;')
w('  try')
w('    ForceDirectories(ExtractFileDir(F));')
w("    S := TFileStream.Create(F + '.part', fmCreate);")
w('    try')
w('      if D <> \'\' then S.WriteBuffer(D[1], Length(D));')
w('    finally')
w('      S.Free;')
w('    end;')
w("    if not RenameFile(F + '.part', F) then DeleteFile(F + '.part');")
w('    if FileExists(F) then Result := F;')
w('  except')
w("    Result := '';")
w('  end;')
w('end;')
w('')
w('end.')
open(OUT, 'w', newline='\n').write('\n'.join(o) + '\n')
print('wrote', OUT, len(named), 'resources,', len(inst), 'install files')
